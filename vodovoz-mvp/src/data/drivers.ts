export function buildDriver(seed: DriverSeed, center: { lat: number; lng: number }, nowIso: string): Driver {
  const reviews: Review[] = REVIEW_POOL.map((r, i) => ({
    ...r,
    id: `${seed.id}-r${i}`,
    at: new Date(Date.parse(nowIso) - (i + 1) * 86400000 * (2 + (seed.id.charCodeAt(1) % 3))).toISOString(),
  })).slice(0, 3 + (seed.id.charCodeAt(1) % 4));

  return {
    id: seed.id,
    userId: seed.id === "d1" ? "u-driver-demo" : undefined,
    name: seed.name,
    phone: seed.phone,
    car: {
      brand: seed.brand,
      model: seed.model,
      plate: seed.plate,
      tankVolume: seed.tankVolume,
      year: seed.year,
      color: seed.color,
    },
    rating: seed.rating,
    ratingCount: seed.ratingCount,
    ordersCompleted: seed.ordersCompleted,
    experienceYears: seed.experienceYears,
    location: { lat: center.lat + seed.dLat, lng: center.lng + seed.dLng },
    online: seed.online,
    verified: seed.verified,
    blocked: false,
    isBot: seed.isBot,
    priceBias: seed.priceBias,
    reviews,
    documents: DOCS.map((d, i) => ({
      ...d,
      status: seed.verified ? "verified" : i < 2 ? "pending" : "missing",
    })),
    createdAt: new Date(Date.parse(nowIso) - seed.experienceYears * 120 * 86400000).toISOString(),
  };
}
